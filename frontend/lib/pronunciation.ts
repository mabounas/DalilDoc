/** Sigles et symboles lus correctement par une voix arabe (darija et arabe). */
const RTL_SYMBOLS: [RegExp, string][] = [
  [/\(?\s*CNIE\s*\)?/g, ""],
  [/\bCEDI\b/g, "مركز تسجيل المعطيات"],
  [/\bPIN\b/g, "الكود السري"],
  [/(?:www\.)?cnie\.ma/gi, "سِي إِنْ إِي إِي، نُقْطَة، مَا"],
  [/(\d)\s*[x×]\s*(\d)/g, "$1 على $2"],
  [/ملم/g, "مِلِّيمِتْر"],
  [/[()]/g, "، "],
];

/** Texte adapté à la lecture : symboles pour l'arabe et la darija, vocalisation pour la darija. */
export function applyPronunciation(text: string, lang: string): string {
  if (lang !== "darija" && lang !== "ar") return text;
  let out = text;
  for (const [pattern, replacement] of RTL_SYMBOLS) out = out.replace(pattern, replacement);
  if (lang === "darija") {
    // Lettres arabes uniquement (la virgule « ، » et les chiffres restent des séparateurs).
    out = out.replace(/[ء-ي]+/g, (word) => DARIJA_LEXICON[word] ?? word);
  }
  return out;
}
